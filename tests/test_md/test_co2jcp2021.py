@pytest.mark.core
def test_forces_match_lammps_on_reference_co2_box():
    """Default (periodic) CO2 force field reproduces the LAMMPS reference forces."""

    ff = CO2JCP2021ForceField()  # zero-config default: bundled 36-CO2 periodic box
    assert ff.na == 108 and ff.n_molecules == 36
    np.testing.assert_allclose(ff.box, 25.263)  # periodic boundary conditions

    forces, _ = ff.compute(ff.positions, np.zeros(3))  # field-free forces
    assert forces.shape == LAMMPS_FORCES.shape

    diff = forces - LAMMPS_FORCES
    assert np.max(np.abs(diff)) < 5e-5  # observed ~1.8e-5 Ha/Bohr (max)
    assert np.sqrt(np.mean(diff**2)) < 1.5e-5  # observed ~6.3e-6 Ha/Bohr (RMS)
